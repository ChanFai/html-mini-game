export function normalizeLocale(value) {
  if (typeof value !== 'string') return null;
  if (/^zh(?:-|$)/i.test(value)) return 'zh-CN';
  if (/^en(?:-|$)/i.test(value)) return 'en';
  return null;
}

export function detectLocale(storage, browserLanguage = 'en') {
  try {
    const raw = storage?.getItem(LANGUAGE_KEY);
    let saved = raw;
    try { saved = JSON.parse(raw); } catch { /* Accept plain values from older settings. */ }
    const supported = normalizeLocale(saved);
    if (supported) return supported;
  } catch { /* Language switching also works when storage is unavailable. */ }
  return normalizeLocale(browserLanguage) || 'en';
}

let locale = 'en';
if (typeof window !== 'undefined') {
  try { locale = detectLocale(window.localStorage, window.navigator.language); }
  catch { locale = normalizeLocale(window.navigator.language) || 'en'; }
}
export const getLocale = () => locale;
export function setLocale(value, storage) {
  const supported = normalizeLocale(value);
  if (!supported) return locale;
  locale = supported;
  try {
    const target = storage === undefined && typeof window !== 'undefined' ? window.localStorage : storage;
    target?.setItem(LANGUAGE_KEY, JSON.stringify(locale));
  } catch { /* Keep the selected language for this session. */ }
  return locale;
}

const normalizeText = (value) => value.trim().replace(/\s+/g, ' ').toLowerCase();
const exact = new Map(Object.entries(MESSAGES).filter(([key]) => !key.includes('{')).map(([key, value]) => [normalizeText(key), value]));
const escapeRegex = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const templates = Object.entries(MESSAGES).filter(([key]) => key.includes('{')).map(([key, value]) => {
  const names = [...key.matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
  const pattern = key.split(/\{\w+\}/).map(escapeRegex).join('(.+?)');
  return { pattern: new RegExp(`^${pattern}$`, 'i'), names, value };
});

export function translate(source, language = locale) {
  if (typeof source !== 'string' || normalizeLocale(language) !== 'zh-CN') return source;
  const trimmed = source.trim();
  const normalized = trimmed.replace(/\s+/g, ' ');
  let translated = exact.get(normalizeText(trimmed));
  if (translated === undefined) {
    for (const entry of templates) {
      const match = entry.pattern.exec(normalized);
      if (!match) continue;
      const values = Object.fromEntries(entry.names.map((name, index) => [name, exact.get(normalizeText(match[index + 1])) ?? match[index + 1]]));
      translated = entry.value.replace(/\{(\w+)\}/g, (_, name) => values[name]);
      break;
    }
  }
  return translated === undefined ? source : source.slice(0, source.indexOf(trimmed)) + translated + source.slice(source.indexOf(trimmed) + trimmed.length);
}

const bindings = new WeakMap();
const ATTRIBUTES = ['aria-label', 'title', 'alt', 'placeholder'];
// Retain source strings while changing only text/attributes, never replacing live controls.
export function translateDOM(root, language = locale) {
  const update = (node, key, current, write) => {
    const records = bindings.get(node) || new Map();
    let record = records.get(key);
    if (!record || current !== record.rendered) record = { source: current };
    const rendered = translate(record.source, language);
    if (current !== rendered) write(rendered);
    record.rendered = rendered;
    records.set(key, record);
    bindings.set(node, records);
  };
  const visit = (node) => {
    if (node.nodeType === 3) {
      if (node.nodeValue.trim()) update(node, 'text', node.nodeValue, (value) => { node.nodeValue = value; });
      return;
    }
    if (node.nodeType !== 1 && node.nodeType !== 11) return;
    if (node.nodeType === 1) {
      if (node.hasAttribute('data-no-i18n')) return;
      for (const attribute of ATTRIBUTES) {
        const value = node.getAttribute(attribute);
        if (value) update(node, attribute, value, (translated) => node.setAttribute(attribute, translated));
      }
      if (['SVG', 'SCRIPT', 'STYLE', 'KBD', 'CANVAS'].includes(node.tagName.toUpperCase())) return;
    }
    for (const child of node.childNodes) visit(child);
  };
  if (root) visit(root);
}
